/* global process */
// Builds src/ui/icons.generated.ts from the Material Symbols (Rounded, weight 400) SVGs.
// Run: node scripts/gen-icons.mjs   (only needed when the icon list below changes)
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "today", "group", "checklist", "trending_up", "account_balance_wallet", "search", "notifications",
  "add", "close", "chevron_left", "chevron_right", "check", "sync_problem", "cloud_off", "inbox",
  "hourglass_top", "lock", "error", "warning", "info", "check_circle", "cancel", "visibility",
  "visibility_off", "light_mode", "dark_mode", "settings", "logout", "language", "call", "sms", "mail",
  "event", "task_alt", "payments", "history", "description", "folder_zip", "credit_card", "help",
  "block", "schedule", "circle", "edit", "bolt", "verified", "pause_circle", "storefront", "shield",
  "monitor_heart", "web", "assignment", "folder", "person", "front_hand", "credit_card_off", "summarize",
  "more_horiz", "add_comment", "event_repeat", "handshake", "sticky_note_2", "dashboard", "key", "tune", "download",
  "person_search", "draft", "event_busy", "power_settings_new", "open_in_new",
];
const dir = "node_modules/@material-symbols/svg-400/rounded";
const read = (file) => {
  const svg = readFileSync(`${dir}/${file}.svg`, "utf8");
  const m = svg.match(/<path d="([^"]+)"/);
  if (!m) throw new Error(`no path in ${file}`);
  return m[1];
};
const out = {};
for (const n of NAMES) {
  let line = { o: read(n) };
  try { line.f = read(`${n}-fill`); } catch { /* no filled variant */ }
  out[n] = line;
}
const body = `// GENERATED by scripts/gen-icons.mjs - do not edit.\n// Source: Material Symbols Rounded 400 (Apache-2.0), bundled so the strict CSP needs no icon font.\nexport const ICON_PATHS: Record<string, { o: string; f?: string }> = ${JSON.stringify(out, null, 1)};\nexport type IconName = ${NAMES.map((n) => JSON.stringify(n)).join(" | ")};\n`;
writeFileSync("src/ui/icons.generated.ts", body);
process.stdout.write(`icons: ${NAMES.length}\n`);
